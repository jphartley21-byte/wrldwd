def write_atomic(path, text, enc="utf8"):
    """Write via a temp file. An editor (Excel) holding the file open must not break the run."""
    tmp = path + ".tmp"
    with open(tmp, "w", encoding=enc, newline="") as f:
        f.write(text)
    try:
        os.replace(tmp, path)
        return path
    except PermissionError:
        alt = path.replace(".csv", "_new.csv")
        os.replace(tmp, alt)
        return alt



def technique_tags(b):
    """Text-derived technique tags for one line. No lyric text is written out."""
    t = []
    ws = [x.lower() for x in cg.words(b)]
    ends = cg.words(b)[-1].lower() if cg.words(b) else ""
    if ends in ("i", "me", "you", "he", "she", "we", "they", "us"):
        t.append("pronoun-end")
    if ends in mg.END_TAG:
        t.append("spoken-end")
    p = bar_profile(b)
    if p["grid"] and p["syl"] > p["grid"][-1]:
        t.append("soft")
    if rt.quad_stats([b])["internal_bars"]:
        t.append("internal")
    if any(x in rt.NUMS for x in ws):
        t.append("number")
    if re.search(r"\b(\w+)-\1\b", b.lower()):
        t.append("reduplication")
    if any(x in qg.TICS for x in ws):
        t.append("tic")
    for m in re.finditer(r"\b([a-z']{3,})\b", b.lower()):
        if m.group(1) in rt.FUNC:
            continue
        if len(re.findall(rf"\b{re.escape(m.group(1))}\b", b.lower())) >= 3:
            t.append("word x3")
            break
    low = b.lower()
    for idiom in cg.IDIOMS:
        if idiom in low:
            t.append("idiom")
            break
    if p["pause"]:
        t.append("mid-bar pause")
    return t


def fmt_num(xs):
    return ".".join(str(x) for x in xs)


# IPA -> plain English, so the rhyme unit reads without knowing phonetics
PLAIN = {"eɪ": "ay", "aɪ": "eye", "ɔɪ": "oy", "əʊ": "oh", "aʊ": "ow", "iː": "ee", "ɪ": "i",
         "e": "eh", "æ": "a", "ɑː": "ah", "ɒ": "o", "ɔː": "aw", "ʌ": "uh", "ʊ": "uu",
         "uː": "oo", "ɜː": "er", "ə": "a", "eə": "air", "ɪə": "ear", "ʊə": "oor", "?": "?"}


def plain(tail):
    return "-".join(PLAIN.get(x, x) for x in tail)


